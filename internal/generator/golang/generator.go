func (g *Generator) Generate(spec *domain.Spec, cfg *config.Config) error {
	outDir := cfg.Output.OutputDir
	if err := os.MkdirAll(outDir, 0755); err != nil {
		return fmt.Errorf("failed to create output directory %s: %w", outDir, err)
	}

	serverName := cfg.Output.ServerName
	if serverName == "" {
		serverName = "mcp-server"
	}

	// 1. Generate go.mod
	goModContent := fmt.Sprintf("module %s\n\ngo 1.22\n", sanitizeModuleName(serverName))
	if err := os.WriteFile(filepath.Join(outDir, "go.mod"), []byte(goModContent), 0644); err != nil {
		return fmt.Errorf("failed to write go.mod: %w", err)
	}

	// 2. Generate README.md
	readmeContent := fmt.Sprintf(`# %s
Generated by toolcraft. Single-binary Model Context Protocol (MCP) server.

## Build

`+"```bash"+`
go build -o %s main.go
`+"```"+`

## Run with Claude Desktop / Cursor / Antigravity

Configure your client to launch the executable:

`+"```json"+`
{
  "mcpServers": {
    "%s": {
      "command": "./%s",
      "env": {
        "%s": "your_api_token_here"
      }
    }
  }
}
`+"```"+`
`, serverName, serverName, serverName, serverName, getEnvVar(cfg))

	if err := os.WriteFile(filepath.Join(outDir, "README.md"), []byte(readmeContent), 0644); err != nil {
		return fmt.Errorf("failed to write README.md: %w", err)
	}

	// 3. Generate main.go
	data := templateData{
		Spec:       spec,
		Config:     cfg,
		ServerName: serverName,
		BaseURL:    spec.BaseURL,
		EnvVar:     getEnvVar(cfg),
	}

	tmpl, err := template.New("go_server").Funcs(templateFuncs).Parse(goServerTemplate)
	if err != nil {
		return fmt.Errorf("failed to parse Go template: %w", err)
	}

	var buf bytes.Buffer
	if err := tmpl.Execute(&buf, data); err != nil {
		return fmt.Errorf("failed to execute Go template: %w", err)
	}

	if err := os.WriteFile(filepath.Join(outDir, "main.go"), buf.Bytes(), 0644); err != nil {
		return fmt.Errorf("failed to write main.go: %w", err)
	}

	return nil
}

func sanitizeModuleName(s string) string {
	s = strings.ToLower(s)
	s = strings.ReplaceAll(s, " ", "-")
	s = strings.ReplaceAll(s, "_", "-")
	return s
}

func getEnvVar(cfg *config.Config) string {
	if cfg.Security.TokenEnvVar != "" {
		return cfg.Security.TokenEnvVar
	}
	return "API_KEY"
}

