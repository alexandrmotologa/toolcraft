package typescript

import (
	"bytes"
	"fmt"
	"os"
	"path/filepath"
	"strings"
	"text/template"

	"github.com/alexandrmotologa/toolcraft/internal/config"
	"github.com/alexandrmotologa/toolcraft/internal/domain"
)

type Generator struct{}

func NewGenerator() *Generator {
	return &Generator{}
}

func (g *Generator) Generate(spec *domain.Spec, cfg *config.Config) error {
	outDir := cfg.Output.OutputDir
	srcDir := filepath.Join(outDir, "src")
	if err := os.MkdirAll(srcDir, 0755); err != nil {
		return fmt.Errorf("failed to create output src directory %s: %w", srcDir, err)
	}

	serverName := cfg.Output.ServerName
	if serverName == "" {
		serverName = "mcp-server"
	}
	pkgName := sanitizePkgName(serverName)

	// 1. Generate package.json
	pkgJSON := fmt.Sprintf(`{
  "name": "%s",
  "version": "%s",
  "description": "Model Context Protocol (MCP) server generated by toolcraft",
  "type": "module",
  "main": "dist/index.js",
  "bin": {
    "%s": "./dist/index.js"
  },
  "scripts": {
    "build": "tsc",
    "start": "node dist/index.js"
  },
  "dependencies": {
    "@modelcontextprotocol/sdk": "^1.6.1",
    "zod": "^3.24.2"
  },
  "devDependencies": {
    "@types/node": "^22.13.9",
    "typescript": "^5.7.3"
  }
}
`, pkgName, cfg.Output.Version, pkgName)

	if err := os.WriteFile(filepath.Join(outDir, "package.json"), []byte(pkgJSON), 0644); err != nil {
		return fmt.Errorf("failed to write package.json: %w", err)
	}

	// 2. Generate tsconfig.json
	tsConfig := `{
  "compilerOptions": {
    "target": "ES2022",
    "module": "NodeNext",
    "moduleResolution": "NodeNext",
    "outDir": "./dist",
    "rootDir": "./src",
    "strict": true,
    "esModuleInterop": true,
    "skipLibCheck": true,
    "forceConsistentCasingInFileNames": true
  },
  "include": ["src/**/*"]
}
`
	if err := os.WriteFile(filepath.Join(outDir, "tsconfig.json"), []byte(tsConfig), 0644); err != nil {
		return fmt.Errorf("failed to write tsconfig.json: %w", err)
	}

	// 3. Generate README.md
	readmeContent := fmt.Sprintf(`# %s
Generated by toolcraft. TypeScript Model Context Protocol (MCP) server package.

## Install and Build

`+"```bash"+`
npm install
npm run build
`+"```"+`

## Run

`+"```bash"+`
npm start
`+"```"+`
`, pkgName)

	if err := os.WriteFile(filepath.Join(outDir, "README.md"), []byte(readmeContent), 0644); err != nil {
		return fmt.Errorf("failed to write README.md: %w", err)
	}

	// 4. Generate src/index.ts
	data := templateData{
		Spec:       spec,
		Config:     cfg,
		ServerName: serverName,
		BaseURL:    spec.BaseURL,
		EnvVar:     getEnvVar(cfg),
	}

	tmpl, err := template.New("ts_server").Funcs(templateFuncs).Parse(tsServerTemplate)
	if err != nil {
		return fmt.Errorf("failed to parse TypeScript template: %w", err)
	}

	var buf bytes.Buffer
	if err := tmpl.Execute(&buf, data); err != nil {
		return fmt.Errorf("failed to execute TypeScript template: %w", err)
	}

	if err := os.WriteFile(filepath.Join(srcDir, "index.ts"), buf.Bytes(), 0644); err != nil {
		return fmt.Errorf("failed to write src/index.ts: %w", err)
	}

	return nil
}

func sanitizePkgName(s string) string {
	s = strings.ToLower(s)
	s = strings.ReplaceAll(s, " ", "-")
	s = strings.ReplaceAll(s, "_", "-")
	return s
}

func getEnvVar(cfg *config.Config) string {
	if cfg.Security.TokenEnvVar != "" {
		return cfg.Security.TokenEnvVar
	}
	return "API_KEY"
}

type templateData struct {
	Spec       *domain.Spec
	Config     *config.Config
	ServerName string
	BaseURL    string
	EnvVar     string
}

var templateFuncs = template.FuncMap{
	"escapeString": func(s string) string {
		return strings.ReplaceAll(s, `"`, `\"`)
	},
	"toZodType": func(p domain.ParameterDefinition) string {
		var zType string
		switch p.Type {
		case "integer", "number":
			zType = "z.number()"
		case "boolean":
			zType = "z.boolean()"
		case "array":
			zType = "z.array(z.string())"
		default:
			zType = "z.string()"
		}

		if len(p.Enum) > 0 {
			enums := make([]string, 0, len(p.Enum))
			for _, e := range p.Enum {
				enums = append(enums, fmt.Sprintf(`"%s"`, strings.ReplaceAll(e, `"`, `\"`)))
			}
			zType = fmt.Sprintf("z.enum([%s])", strings.Join(enums, ", "))
		}

		if !p.Required {
			zType += ".optional()"
		}
		if p.Description != "" {
			zType += fmt.Sprintf(`.describe("%s")`, strings.ReplaceAll(p.Description, `"`, `\"`))
		}
		return zType
	},
}

const tsServerTemplate = `// Code generated by toolcraft. DO NOT EDIT.
import { McpServer } from "@modelcontextprotocol/sdk/server/mcp.js";
import { StdioServerTransport } from "@modelcontextprotocol/sdk/server/stdio.js";
import { z } from "zod";

const serverName = "{{ .ServerName }}";
const serverVersion = "{{ .Config.Output.Version }}";
const defaultBaseUrl = "{{ .BaseURL }}";
const authEnvVar = "{{ .EnvVar }}";
const readOnlyMode = {{ .Config.Hardening.ReadOnly }};

const server = new McpServer({
  name: serverName,
  version: serverVersion,
});

{{ range .Spec.Tools }}
// Tool: {{ .ID }}
server.tool(
  "{{ .ID }}",
  "{{ escapeString .Description }}",
  {
{{- range .Parameters }}
    "{{ .Name }}": {{ toZodType . }},
{{- end }}
{{- if .RequestBody }}
{{- range .RequestBody.Properties }}
    "{{ .Name }}": {{ toZodType . }},
{{- end }}
{{- end }}
  },
  async (args: Record<string, any>) => {
    {{- if and $.Config.Hardening.ReadOnly (not .ReadOnly) }}
    return {
      content: [
        {
          type: "text",
          text: "Error: tool '{{ .ID }}' is blocked because server is running in strict read-only mode.",
        },
      ],
      isError: true,
    };
    {{- else }}
    const baseUrl = (process.env.API_BASE_URL || defaultBaseUrl || "http://localhost:8080").replace(/\/$/, "");
    let path = "{{ .Path }}";
    const queryParams = new URLSearchParams();
    const bodyPayload: Record<string, any> = {};

    for (const [key, value] of Object.entries(args)) {
      if (value === undefined || value === null) continue;
      const placeholder = "{" + key + "}";
      if (path.includes(placeholder)) {
        path = path.replace(placeholder, encodeURIComponent(String(value)));
      } else {
{{- if .RequestBody }}
        bodyPayload[key] = value;
{{- else }}
        queryParams.append(key, String(value));
{{- end }}
      }
    }

    let targetUrl = baseUrl + path;
    const queryString = queryParams.toString();
    if (queryString) {
      targetUrl += "?" + queryString;
    }

    const headers: Record<string, string> = {
      "User-Agent": "toolcraft-mcp-server/1.0",
      "Accept": "application/json",
    };

    const token = process.env[authEnvVar];
    if (token) {
      headers["Authorization"] = "Bearer " + token;
    }

    const fetchOptions: RequestInit = {
      method: "{{ .Method }}",
      headers,
    };

    if (Object.keys(bodyPayload).length > 0) {
      headers["Content-Type"] = "application/json";
      fetchOptions.body = JSON.stringify(bodyPayload);
    }

    try {
      const response = await fetch(targetUrl, fetchOptions);
      const text = await response.text();
      return {
        content: [
          {
            type: "text",
            text: text || "HTTP " + response.status,
          },
        ],
        isError: !response.ok,
      };
    } catch (err: any) {
      return {
        content: [
          {
            type: "text",
            text: "Request failed: " + (err?.message || String(err)),
          },
        ],
        isError: true,
      };
    }
    {{- end }}
  }
);
{{ end }}

async function main() {
  const transport = new StdioServerTransport();
  await server.connect(transport);
  console.error(serverName + " v" + serverVersion + " listening over stdio");
}

main().catch((error) => {
  console.error("Fatal server error:", error);
  process.exit(1);
});
`
